"""Regenerates runtime/remote/constraints.txt: the runtime's dependencies on
SSH servers, one set per Python version the server may have (3.9, 3.10, 3.11
and newer), every version pinned and every file pinned by its sha256.

bootstrap.sh installs them with --require-hashes, so the packages are the
same files whichever index they come from (PyPI, or a mirror in mainland
China, where PyPI is often slow).

    uv run --with packaging runtime/remote/lock.py            keep the versions, refresh the hashes
    uv run --with packaging runtime/remote/lock.py --upgrade  newest versions (then run the tests on 3.9, 3.10, 3.12)

Entries that can't apply on a Linux or macOS server (Windows, and the
resolver's branches for Pythons outside each set) are left out.
"""

import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PYPROJECT = HERE.parent / "pyproject.toml"
LOCK = HERE / "constraints.txt"

# (heading, marker for that set, the oldest Python it's resolved for, Pythons it covers)
GROUPS = [
    ("Python 3.11 and newer", 'python_version >= "3.11"', "3.11", ["3.11.0", "3.12.0", "3.13.0", "3.14.0", "3.15.0", "3.16.0"]),
    ("Python 3.10", 'python_version == "3.10"', "3.10", ["3.10.0", "3.10.99"]),
    ("Python 3.9", 'python_version < "3.10"', "3.9", ["3.9.0", "3.9.99"]),
]


def on_a_server(marker: str, pythons: list) -> bool:
    """Whether a Linux or macOS server with one of these Pythons can match the marker."""
    from packaging.markers import Marker

    m = Marker(marker)
    for full in pythons:
        for system, platform in (("Linux", "linux"), ("Darwin", "darwin")):
            for machine in ("x86_64", "aarch64", "arm64"):
                env = {
                    "python_version": ".".join(full.split(".")[:2]), "python_full_version": full,
                    "sys_platform": platform, "platform_system": system, "platform_machine": machine,
                    "os_name": "posix", "implementation_name": "cpython", "platform_python_implementation": "CPython",
                }
                if m.evaluate(env):
                    return True
    return False


REQ = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;\\]+)\s*(?:;\s*(.*?))?\s*\\?\s*$")


def entries(text: str):
    """(name, version, marker or None, [hash lines]) for each requirement."""
    out = []
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line[0].isspace():
            h = line.strip().rstrip("\\").strip()
            if h.startswith("--hash=") and out:
                out[-1][3].append(h)
            continue
        m = REQ.match(line)
        if not m:
            raise SystemExit(f"Can't read this line of the lock: {line!r}")
        out.append((m.group(1), m.group(2), m.group(3), []))
    return out


def current_pins() -> dict:
    """The versions in the lock now, per group."""
    pins = {marker: [] for _, marker, _, _ in GROUPS}
    if LOCK.exists():
        for name, version, marker, _ in entries(LOCK.read_text()):
            for _, group, _, pythons in GROUPS:
                if marker and group in marker and on_a_server(marker, pythons):
                    pins[group].append(f"{name}=={version}")
    return pins


def compile_group(marker: str, python: str, pins: list, upgrade: bool) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        cmd = ["uv", "pip", "compile", str(PYPROJECT), "--universal", "--python-version", python,
               "--generate-hashes", "--no-header", "--no-annotate", "--quiet"]
        if pins and not upgrade:
            # Only for this Python: the set for newer Pythons may differ.
            constraints = Path(tmp) / "pins.txt"
            constraints.write_text("".join(f"{p} ; {marker}\n" for p in pins))
            cmd += ["-c", str(constraints)]
        return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def main() -> None:
    upgrade = "--upgrade" in sys.argv
    pins = current_pins()
    lines = [
        "# Tandem on an SSH server: the runtime's dependencies, one set per Python",
        "# version the server may have, chosen by the markers. Every version is",
        "# pinned and every file is pinned by its sha256: bootstrap.sh installs with",
        "# --require-hashes, so the files are the same from PyPI or a mirror.",
        "# Generated by runtime/remote/lock.py; don't edit by hand.",
    ]
    for heading, marker, python, pythons in GROUPS:
        lines += ["", f"# {heading}"]
        for name, version, own, hashes in entries(compile_group(marker, python, pins[marker], upgrade)):
            both = f"{marker} and ({own})" if own else marker
            if not on_a_server(both, pythons):
                continue
            lines.append(f"{name}=={version} ; {both} \\")
            lines += [f"    {h} \\" for h in hashes[:-1]] + [f"    {hashes[-1]}"]
    LOCK.write_text("\n".join(lines) + "\n")
    print(f"{LOCK.relative_to(HERE.parent.parent)}: {sum(1 for l in lines if '==' in l)} pins")


if __name__ == "__main__":
    main()
